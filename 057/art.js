function bond([x1, y1], [x2, y2], n) {
  const dx = x2 - x1, dy = y2 - y1, L = Math.hypot(dx, dy) || 1, ox = -dy / L * 3.2, oy = dx / L * 3.2;
  const offs = n === 3 ? [-1, 0, 1] : n === 2 ? [-.5, .5] : [0];
  return offs.map(k => `<line x1="${(x1 + ox * k).toFixed(1)}" y1="${(y1 + oy * k).toFixed(1)}" x2="${(x2 + ox * k).toFixed(1)}" y2="${(y2 + oy * k).toFixed(1)}"/>`).join("");
}
const cache = {};
function molSVG(id) {
  if (cache[id] !== undefined) return cache[id];
  const m = MOL[id]; if (!m) return (cache[id] = "");
  const pts = m.a.map(([, x, y]) => [x, y]);
  const bonds = m.b.map(([i, j, n = 1]) => bond(pts[i], pts[j], n)).join("");
  const atoms = m.a.map(([el, x, y]) => { const r = R(el); return `<circle cx="${x}" cy="${y}" r="${r}" fill="${COL[el] || "#ccc"}"/><circle cx="${(x - r * .32).toFixed(1)}" cy="${(y - r * .36).toFixed(1)}" r="${(r * .38).toFixed(1)}" fill="#fff" opacity=".42"/>`; }).join("");
  return (cache[id] = `<svg class="cmol" viewBox="0 0 100 100" aria-hidden="true"><g stroke="rgba(236,239,245,.55)" stroke-width="2.4" stroke-linecap="round">${bonds}</g>${atoms}</svg>`);
}
